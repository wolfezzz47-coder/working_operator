using System.Text;

public class MyMatrix
{
    // readonly 2D array to store matrix data - це 
    // означає, що після ініціалізації масиву його
    // розмір не можна змінити, але значення
    // елементів можна змінювати.
    private readonly double[,] _data; // означає, що поле _data є приватним і доступне лише всередині класу MyMatrix.

    public MyMatrix(int rows, int cols) // Конструктор класу MyMatrix, який приймає кількість рядків і стовпців як параметри.
    {
        if (rows <= 0)
            throw new ArgumentOutOfRangeException(nameof(rows), "Кількість рядків має бути більшою за нуль."); 
        // розкидає виняток, якщо кількість рядків або стовпців менша або дорівнює нулю.
        if (cols <= 0)
            throw new ArgumentOutOfRangeException(nameof(cols), "Кількість стовпців має бути більшою за нуль.");
        // розкидає виняток, якщо кількість рядків або стовпців менша або дорівнює нулю.

        _data = new double[rows, cols]; // ініціалізує 2D масив для зберігання даних матриці з заданою кількістю рядків і стовпців.
    }

    public int Rows => _data.GetLength(0); // властивість, яка повертає кількість рядків у матриці, використовуючи метод GetLength(0) для отримання розміру першого виміру масиву.
    public int Cols => _data.GetLength(1); // властивість, яка повертає кількість стовпців у матриці, використовуючи метод GetLength(1) для отримання розміру другого виміру масиву.

    public double this[int row, int col] // індексатор, який дозволяє доступ до елементів матриці за допомогою синтаксису m[row, col].
    {
        get => _data[row, col]; // повертає значення елемента матриці за вказаними індексами рядка і стовпця.
        set => _data[row, col] = value; // встановлює значення елемента матриці за вказаними індексами рядка і стовпця.
    }

    public MyMatrix Transpose() // метод, який повертає транспоновану матрицю (рядки стають стовпцями і навпаки).
    {
        var result = new MyMatrix(Cols, Rows); // створює нову матрицю з кількістю рядків, що дорівнює кількості
                                               // стовпців оригінальної матриці, і кількістю стовпців, що дорівнює кількості рядків оригінальної матриці.
        for (int i = 0; i < Rows; i++)
            for (int j = 0; j < Cols; j++)
                result[j, i] = _data[i, j];
        return result;
    }

    public override string ToString() // перевизначення методу ToString() для надання зручного текстового представлення матриці.
    {
        var sb = new StringBuilder(); // StringBuilder
                                      // використовується для
                                      // ефективного створення
                                      // рядків, особливо коли
                                      // потрібно багаторазово
                                      // додавати текст.
        for (int i = 0; i < Rows; i++) // зовнішній цикл для проходження по рядках матриці
        {
            for (int j = 0; j < Cols; j++) // внутрішній цикл для проходження по стовпцях матриці
                sb.Append(_data[i, j]).Append(j < Cols - 1 ? "\t" : ""); // додає значення елемента матриці до StringBuilder,
                                                                         // використовуючи табуляцію ("\t") для розділення елементів
                                                                         // у рядку, крім останнього елемента.
            if (i < Rows - 1) // додає новий рядок після кожного рядка матриці, крім останнього.
                sb.AppendLine(); // додає новий рядок після кожного рядка матриці, крім останнього.
        }
        return sb.ToString();
    }
}
